def main() -> None:
    with urllib.request.urlopen("https://ummahapi.com/api/duas") as response:
        data = json.load(response)

    duas = data["data"]["duas"]
    out = []

    for dua in duas:
        dua_id = dua["id"]
        if dua_id not in AR:
            raise KeyError(f"Missing Arabic translation for dua id {dua_id}")
        title, translation = AR[dua_id]
        out.append(
            {
                "id": dua_id,
                "titleAr": title,
                "translationAr": translation,
            }
        )

    output_path = "assets/data/duaa_ar.json"
    with open(output_path, "w", encoding="utf-8") as file:
        json.dump(out, file, ensure_ascii=False, indent=2)
        file.write("\n")

    print(f"Wrote {len(out)} entries to {output_path}")


if __name__ == "__main__":
    main()
